 assert.equal(await page.locator('#report [onerror]').count(),0,'导入内容未转义');assert.equal(await page.locator('#report .character').count(),1);assert.equal(await page.locator('#showAmount').isDisabled(),true);
 await page.evaluate(()=>MTypeApp.loadData({orders:[]}));assert.equal(await page.locator('#questions fieldset').count(),4);assert.equal(await page.locator('#exportButton').isDisabled(),true);
