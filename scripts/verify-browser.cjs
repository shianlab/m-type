 await page.locator('#gallery').evaluate(dialog=>{dialog.style.maxHeight='none';dialog.style.position='absolute';dialog.style.top='0';dialog.style.bottom='auto';dialog.style.margin='0 auto';});
 await page.locator('#gallery').screenshot({path:path.join(root,'output/16-personalities.png')});
 await page.locator('#gallery').evaluate(dialog=>dialog.removeAttribute('style'));
 await page.getByRole('button',{name:'关闭人格图鉴'}).click();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'手机端横向溢出');
 await page.screenshot({path:path.join(root,'output/mobile-preview.png'),fullPage:true});
 const png=await page.evaluate(()=>MTypeApp.exportReport(false));
