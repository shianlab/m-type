 await page.locator('#showAmount').check();assert.equal(await page.locator('.stat').count(),4);
 await page.locator('#resetDemo').click();
 const unsafe={orders:Array.from({length:5},(_,i)=>({id:String(i),status:'completed',orderedAt:`2026-09-0${i+1}T12:30:00+08:00`,discountAmount:0,items:[{productName:'<img src=x onerror=alert(1)>',quantity:1,tags:['classic']}]}))};
